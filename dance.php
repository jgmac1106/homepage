So they danced to rhythm 
  held in cadence by incessant chatter of air raid sirens keeping time in shadows of collapsing buildings raising a finger to a sun not setting in dreams who can no longer sing to Mercy, Pity, Peace, and Love 
So they danced to baroque violins marching along fifty operas belting in four seasons to children lost under Eastern shadows
 So they danced in Kharkiv, Kherson, and Kupiansk. 
  A Defender half step in Donetsk spitting dozens against a veiled goose step dripping from rising light in broken skies screaming with a devil's rage painted on bristles dipped into a palate of tyranny
 Tallest leaves atop a hollowed out tree, umbras drip from heartless cavities wrapped in falling bark, but the leaf still drinks, fingers touching sun above fields where thorny devils, small spiny lizards lurk, worming through soil
 So they danced on banks of the Siverskyi Donets, busy bodies of Kramatorsk doing a Dougie of Defenders dreams
  Hulking mighty stings through the night, witness to the martyrs of misery
  Is this not our Paradise Lost, broken but a beat remains?
  riding backwards down a number line in memories of collective language forgotten, a doll, one eye missing, hanging tired in a listless hand of a soot covered child
   darkened by the coal deep beneath her feet and the terrors falling above. No fear for them, nor will they grieve, but grace and bounty still denied
  So they danced 
   Can we not see the beauty in the time of death and loss? Not of a candles burning, but of wicks untouched by a fiery embrace of true solemn purpose
   No one can take your dance away for the heavens know
    Moscow will fall through Crimea
   The Gods, old and new know.
   A song is also a weapon. A dance, poetic verse to joy and struggle
    We say thank you out loud without speaking these terms. Only through movement can you find the understanding brought by 
    pomegranates growing as a mind bathes in a cast iron tub, lavender and sage, strewn from a blown out buildings
   So they danced
    to the cost of Karpivka's liberation. Feet who could not patter so other could still sing. Still Dance, Still breath in Freedom's clutch, a purse held tightly to the chest
     Can heaven not arise without hell's revival 
   carried in backslides of a bankhead bounce
    torments of angels who know the beauty must arise from the abyss
     a deep strike in a phantom's cold embrace turning Samara fields into darken columns of a Defenders hope
   So they danced to silver doused split tongues on Princes stolen on lighting of a Kalishnikovs loitering in the sky
    only to see raspberry driven rage seep deep into landscapes littered in tatters of imperial dreams
   and a stray dog walks by, tail wagging oblivious to our fractured world. And in that moment we know
   We must keep this dance moving
