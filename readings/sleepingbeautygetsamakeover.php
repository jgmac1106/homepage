					"> </a><a data-auto="ep_link" href="https://web-a-ebscohost-com.scsu.idm.oclc.org/ehost/delivery?sid=c43b1425-7a56-4182-bc1b-885943e30abb%40sessionmgr4006&amp;vid=3&amp;ReturnUrl=https%3a%2f%2fweb.a.ebscohost.com%2fehost%2fdetail%2fdetail%3fvid%3d2%26sid%3dc43b1425-7a56-4182-bc1b-885943e30abb%2540sessionmgr4006%26bdata%3dJnNpdGU9ZWhvc3QtbGl2ZSZzY29wZT1zaXRl#bib1" id="ref_linkbib1" title="1">1</a>]; Berger, Wallis, &amp; Watson, [<a id="bib2up
					"> </a><a data-auto="ep_link" href="https://web-a-ebscohost-com.scsu.idm.oclc.org/ehost/delivery?sid=c43b1425-7a56-4182-bc1b-885943e30abb%40sessionmgr4006&amp;vid=3&amp;ReturnUrl=https%3a%2f%2fweb.a.ebscohost.com%2fehost%2fdetail%2fdetail%3fvid%3d2%26sid%3dc43b1425-7a56-4182-bc1b-885943e30abb%2540sessionmgr4006%26bdata%3dJnNpdGU9ZWhvc3QtbGl2ZSZzY29wZT1zaXRl#bib2" id="ref_linkbib2" title="2">2</a>]).
 The value of individual characteristics such as competence, 
intelligence, integrity, and wisdom depart from traditional teachings in
 fairytales that tell about the classic 
beautiful-princess-rescued-by-handsome-powerful-prince storylines (Wood,
 [<a id="bib8up
					"> </a><a data-auto="ep_link" href="https://web-a-ebscohost-com.scsu.idm.oclc.org/ehost/delivery?sid=c43b1425-7a56-4182-bc1b-885943e30abb%40sessionmgr4006&amp;vid=3&amp;ReturnUrl=https%3a%2f%2fweb.a.ebscohost.com%2fehost%2fdetail%2fdetail%3fvid%3d2%26sid%3dc43b1425-7a56-4182-bc1b-885943e30abb%2540sessionmgr4006%26bdata%3dJnNpdGU9ZWhvc3QtbGl2ZSZzY29wZT1zaXRl#bib8" id="ref_linkbib8" title="8">8</a>]).
 Through these stories, the ideals of an attractive appearance, 
especially feminine appearance, are cultural constructions reflecting 
primarily hegemonic standards.</p><p class="body-paragraph" data-auto="body_paragraph">Eighteenth
 century fairytales, for example, were used to teach boys and girls the 
appropriate gender roles that reflected the values and attitudes of the 
society (e.g., Bettelheim, [<a id="bib3up
					"> </a><a data-auto="ep_link" href="https://web-a-ebscohost-com.scsu.idm.oclc.org/ehost/delivery?sid=c43b1425-7a56-4182-bc1b-885943e30abb%40sessionmgr4006&amp;vid=3&amp;ReturnUrl=https%3a%2f%2fweb.a.ebscohost.com%2fehost%2fdetail%2fdetail%3fvid%3d2%26sid%3dc43b1425-7a56-4182-bc1b-885943e30abb%2540sessionmgr4006%26bdata%3dJnNpdGU9ZWhvc3QtbGl2ZSZzY29wZT1zaXRl#bib3" id="ref_linkbib3" title="3">3</a>]; Crabb &amp; Bielawski, [<a id="bib4up
					"> </a><a data-auto="ep_link" href="https://web-a-ebscohost-com.scsu.idm.oclc.org/ehost/delivery?sid=c43b1425-7a56-4182-bc1b-885943e30abb%40sessionmgr4006&amp;vid=3&amp;ReturnUrl=https%3a%2f%2fweb.a.ebscohost.com%2fehost%2fdetail%2fdetail%3fvid%3d2%26sid%3dc43b1425-7a56-4182-bc1b-885943e30abb%2540sessionmgr4006%26bdata%3dJnNpdGU9ZWhvc3QtbGl2ZSZzY29wZT1zaXRl#bib4" id="ref_linkbib4" title="4">4</a>]; Fox, [<a id="bib5up
					"> </a><a data-auto="ep_link" href="https://web-a-ebscohost-com.scsu.idm.oclc.org/ehost/delivery?sid=c43b1425-7a56-4182-bc1b-885943e30abb%40sessionmgr4006&amp;vid=3&amp;ReturnUrl=https%3a%2f%2fweb.a.ebscohost.com%2fehost%2fdetail%2fdetail%3fvid%3d2%26sid%3dc43b1425-7a56-4182-bc1b-885943e30abb%2540sessionmgr4006%26bdata%3dJnNpdGU9ZWhvc3QtbGl2ZSZzY29wZT1zaXRl#bib5" id="ref_linkbib5" title="5">5</a>]; Pescosolido, Grauerholz, &amp; Milkie, [<a id="bib7up
					"> </a><a data-auto="ep_link" href="https://web-a-ebscohost-com.scsu.idm.oclc.org/ehost/delivery?sid=c43b1425-7a56-4182-bc1b-885943e30abb%40sessionmgr4006&amp;vid=3&amp;ReturnUrl=https%3a%2f%2fweb.a.ebscohost.com%2fehost%2fdetail%2fdetail%3fvid%3d2%26sid%3dc43b1425-7a56-4182-bc1b-885943e30abb%2540sessionmgr4006%26bdata%3dJnNpdGU9ZWhvc3QtbGl2ZSZzY29wZT1zaXRl#bib7" id="ref_linkbib7" title="7">7</a>]).
 Because children's stories are used primarily as a way to assimilate 
children into the culture, it is important to teach students to question
 standards that reflect and respect only people with certain physical 
attributes. Many different types of courses address issues of 
self-concept, perception, and identity. These courses often introduce 
the idea that attractive, young, and able-bodied individuals are valued 
more than others and then point out that less attractive, older, and 
disabled individuals are often devalued and even discriminated against.</p><p class="body-paragraph" data-auto="body_paragraph">Therefore,
 this activity asks students to recognize the culturally established 
norms of beauty, gender roles, age, ethnicity, and ability and provides 
an opportunity for students to reconstruct fairytales to reflect an 
integrated society consisting of a diverse array of attributes.</p><a id="AN0032771234-4"> </a><span class="medium-bold"><h3><a data-auto="ep_link" href="#toc" onclick="FocusElement('toc');" id="hd_toc_AN0032771234-4" title="The Activity">The Activity</a></h3></span><p class="body-paragraph" data-auto="body_paragraph"><a id="AN0032771234-5"> </a><span class="medium-bold"></span></p><h3><a data-auto="ep_link" href="#toc" onclick="FocusElement('toc');" id="hd_toc_AN0032771234-5" title="Materials">Materials</a></h3><p class="body-paragraph" data-auto="body_paragraph"></p><ul><li><span class="medium-normal"> 1. Books of Grimm's fairytales (e.g., Sleeping Beauty; Rapunzel; Cinderella; Snow White). I use the </span><em>Little Golden Books</em><span class="medium-normal"> because they synthesize the tales in a concise format, and are filled with pictures and language that are easy to translate.</span></li><p class="body-paragraph" data-auto="body_paragraph"></p><li><span class="medium-normal"> 2. Writing materials (two options):</span></li><p class="body-paragraph" data-auto="body_paragraph"></p><li><span class="medium-normal"> a. stapled large white pages of paper in the format of a book along with crayons or markers</span></li><p class="body-paragraph" data-auto="body_paragraph"></p><li><span class="medium-normal"> b. overhead transparency pages and markers.</span></li><p class="body-paragraph" data-auto="body_paragraph"></p><li><span class="medium-normal">
 3. The primary article "The Pervasiveness and Persistence of the 
Feminine Beauty Ideal in Children's Fairy Tales" by Baker-Sperry and 
Grauerholz ([</span><a id="bib1up
					"> </a><a data-auto="ep_link" href="https://web-a-ebscohost-com.scsu.idm.oclc.org/ehost/delivery?sid=c43b1425-7a56-4182-bc1b-885943e30abb%40sessionmgr4006&amp;vid=3&amp;ReturnUrl=https%3a%2f%2fweb.a.ebscohost.com%2fehost%2fdetail%2fdetail%3fvid%3d2%26sid%3dc43b1425-7a56-4182-bc1b-885943e30abb%2540sessionmgr4006%26bdata%3dJnNpdGU9ZWhvc3QtbGl2ZSZzY29wZT1zaXRl#bib1" id="ref_linkbib1" title="1">1</a><span class="medium-normal">]). Additional articles are listed for your consideration in the reference section.</span></li></ul><a id="AN0032771234-6"> </a><span class="medium-bold"><h3><a data-auto="ep_link" href="#toc" onclick="FocusElement('toc');" id="hd_toc_AN0032771234-6" title="Directions">Directions</a></h3></span><p class="body-paragraph" data-auto="body_paragraph"></p><p class="body-paragraph" data-auto="body_paragraph"> </p><table><tbody><tr><td>Step One:</td><td>Divide students into groups of three or four persons each.</td></tr><tr><td>Step Two:</td><td>Provide
 each group with one of the fairy tale books and either the large blank 
paper book you have assembled or overhead transparencies.</td></tr><tr><td>Step Three:</td><td>Before
 lecturing or discussing the beauty ideal, have students do a form of 
content analysis on the fairy tale focusing on and listing key concepts 
that seem to be present regarding:</td></tr><tr><td></td><td><list list-type="Bullet"><list-item><p>a. Beauty</p></list-item><list-item><p>b. gender roles</p></list-item><list-item><p>c. age</p></list-item><list-item><p>d. race</p></list-item><list-item><p>e. ability</p></list-item><list-item><p>f. economic status</p></list-item><list-item><p>g. issues of power.</p></list-item></list></td></tr><tr><td>Step Four:</td><td>Compile
 students' lists through class discussion, making a master list on the 
board. Create questions to get students thinking critically. Examples 
include:</td></tr><tr><td></td><td><list list-type="Bullet"><list-item><p>a. What is the link between beauty, age, ethnicity, ability, and goodness in these stories?</p></list-item><list-item><p>b. What is the potential danger associated with beauty and desirability?</p></list-item><list-item><p>c.
 What role do you think the representation of beauty, age, ethnicity, or
 ability plays in socially created norms? What is the result of the 
creation of these types of norms?</p></list-item><list-item><p>d. What 
is the relationship between beauty/age/ethnicity/ability and economic 
privilege, intelligence, motive, honesty, integrity, and power?</p></list-item><list-item><p>e. How is the possession of beauty/age/ethnicity/ability rewarded? How is the lack of beauty/age/ethnicity/ability punished?</p></list-item><list-item><p>f. What gender roles are presented in the fairytales?</p></list-item></list></td></tr><tr><td>Step Five:</td><td>Using
 information from the articles listed in the reference section, lecture 
on the pervasiveness and persistence of beauty/age/ethnicity/ability 
used in these stories to perpetuate the hegemonic beauty ideal. 
Formulate possible lecture topics about:</td></tr><tr><td></td><td><list list-type="Bullet"><list-item><p>a. social status</p></list-item><list-item><p>b. female and male beauty standards</p></list-item><list-item><p>c. gender roles</p></list-item><list-item><p>d. ageism</p></list-item><list-item><p>e. how different forms of media maintain a socially constructed notion of beauty and gender roles</p></list-item><list-item><p>f. power in relationships</p></list-item><list-item><p>g. stereotypical images (e.g., body, clothing, hair, eye color, strength, age).</p></list-item></list></td></tr><tr><td>Step Six:</td><td>Instruct
 students to rewrite the fairytale replacing words that present 
stereotypical implications of attractiveness, intelligence, moral 
character, and race. For example, instead of saying "Once upon a time, 
in a land far, far away, there lived a beautiful princess who was as 
beautiful as she was kind ...", retell the story to reflect a broader 
array of individuals. Students might change the line to read: "Once upon
 a time, in an inner city project, there lived a 250 pound gang-banger 
who was as smart as she was kind ...." (It is important to note that the
 rewriting of these fairytales often results in the emergence of other 
types of stereotypes, making it necessary to call attention to these 
stereotypes when they arise.)</td></tr><tr><td></td><td>Allow students time to finish translating the story and to draw/write it on either the papers or transparencies.</td></tr><tr><td>Step Seven:</td><td>Have each group present their revised fairytale to the class.</td></tr><tr><td>Step Eight:</td><td>After all groups have presented their revised fairytales, debrief.</td></tr></tbody></table> <p></p><a id="AN0032771234-7"> </a><span class="medium-bold"><h3><a data-auto="ep_link" href="#toc" onclick="FocusElement('toc');" id="hd_toc_AN0032771234-7" title="Debriefing">Debriefing</a></h3></span><p class="body-paragraph" data-auto="body_paragraph">To
 debrief, ask questions such as: How did you feel rewriting these 
classic fairytales? What things did you find most difficult to rewrite 
and why? What were the easiest changes to make? Were they related to 
culture? Age? Ability? Appearance? Gender? Character? Why do you think 
these were easiest? What stereotypes became most evident to you while 
doing this activity? (e.g., Witches are ugly and unmarried; Males rescue
 women/women need rescuing; Stepmothers are evil and do not 
stepchildren; Stepsisters are unattractive self-centered; Stepfamilies 
are unhappy; Ogres (country folk) are uneducated or dumb; Characters in 
fairytales are white; Women are helpless; Heroes are handsome; Villagers
 are intolerant; Kings are often clueless and selfish; Queens are often 
conniving; Wolves eat people; and Talking animals can't be trusted).</p><a id="AN0032771234-8"> </a><span class="medium-bold"><h3><a data-auto="ep_link" href="#toc" onclick="FocusElement('toc');" id="hd_toc_AN0032771234-8" title="Appraisal">Appraisal</a></h3></span><p class="body-paragraph" data-auto="body_paragraph">This
 activity has proven effective in challenging students to critically 
evaluate the acceptance of certain hegemonic norms in fairytales. 
Students often state in evaluations that the activity provided a unique 
and creative way to consider issues of gender roles, beauty, age, 
ethnicity, and ability as they impact the value we place on individuals.
 In fact, this activity challenges students to recognize and critically 
assess the role of language in the creation of power issues, muted 
groups, and issues of silencing by the dominant culture. Although 
students are often unnerved by the realization of their own acceptance 
of these hegemonic stereotypes, most still find this activity fun, 
rewarding, valuable, intriguing, interesting, and challenging. Many 
claim long-term impact of the activity in making theoretical aspects of 
the social construction of hegemonic values within our culture real. 
Students report being surprised at how difficult it is to retell these 
fairytales in ways that do not perpetuate hegemonic norms. Ultimately, 
this activity fosters excellent classroom discussion and engages a 
diverse student population as they seek to represent their diversity in 
the retelling of these time-honored fairytales.</p><a id="AN0032771234-9"> </a><span class="medium-bold"><a data-auto="ep_link" href="#toc" id="ref_toc" title=" References  "> References  </a></span><p class="body-paragraph"><em><a id="bib1"> </a><a data-auto="ep_link_bt" href="https://web-a-ebscohost-com.scsu.idm.oclc.org/ehost/delivery?sid=c43b1425-7a56-4182-bc1b-885943e30abb%40sessionmgr4006&amp;vid=3&amp;ReturnUrl=https%3a%2f%2fweb.a.ebscohost.com%2fehost%2fdetail%2fdetail%3fvid%3d2%26sid%3dc43b1425-7a56-4182-bc1b-885943e30abb%2540sessionmgr4006%26bdata%3dJnNpdGU9ZWhvc3QtbGl2ZSZzY29wZT1zaXRl#bib1up" id="bib_upbib1" title="1">1</a>
