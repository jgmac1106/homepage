 this case we see a sector of human experience being excluded from 
analytical gaze. The exclusion is made for participants in the project 
on their own behalf but without consulting them in any way.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">That
 is the problem of the protection of the privacy of human subjects of 
