represents a unique partnership between the university and the 
Intelligence Community (IC) and the U.S. Department of Defense. CASL's 
mission is to serve the nation by improving the language performance of 
the IC and DoD workforce. CASL is now the largest language research 
center in the United States. (<a href="http://www.casl.umd.edu/">http://www.casl.umd.edu/</a>)</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">The
 authors have nothing to do with this center; indeed, little is actually
 known about this center with the Kafkaesque 'Castle' acronym – CASL. 
Little is known about their activities beyond their size ('the largest')
 and a few glimpses of the scope of their activities we gleaned from 
reading the request for proposals (RFP) that was closely circulated 
around linguistics departments in the Washington area. Beyond telling us
 that they are now the tail wagging the U.S. linguistic research dog, 
the website tells us precious little beyond the need to qualify for U.S.
 security clearance. In the foundational RFP as well as in job 
announcements posted as early as the 2004 meetings of the American 
Association of Applied Linguistics (AAAL), however, they make much of 
very rich kinds of data a linguist can get access to when signing up 
with them in the most exciting and adventurous of 'field conditions.' 
Can we be justified in thinking that such places as Abu Graib lie in the
 background of such adventures? Because they were so meticulous in 
highlighting intriguing data that would never be available elsewhere, it
 seems clear that one could expect total freedom from those nasty IRB 
restrictions on the use of human subjects. Naturally, national security 
is at stake.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">When
