 with fieldwork written up as an ethnography of speaking ([17]), then an
 essay in what came to be called New Literacy Studies ([18]), our 
linguistic ethnography evolved into what we now call nexus analysis. As 
we will describe in more detail below, we found that there was no single
 point at which we could address problems of societal discrimination, 
institutional structure, and social change with any sense that this 
point was the fulcrum point around which everything else rotated. Even 
though our predilection was for close social‐interactional studies of 
face‐to‐face encounters, each such point – a classroom, a dormitory, 
university application and acceptance procedures, high school offices – 
was linked into a network that cumulatively was leading to endemic, 
institutional, social discrimination. In many cases the actions and 
intentions of players at each point were decidedly not discriminatory. 
The problem we faced was finding a way to proceed in the face of this 
kind of complex and distributed social problem. While at the time we did
 the work we did not have a name for it, we have since come to call this
 work nexus analysis. As we have written ([21]: viii) a nexus analysis 
is the:</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">mapping
 of semiotic cycles of people, discourses, places, and mediational means
 involved in the social action we are studying. We ... use the term 
'nexus of practice' to focus on the point at which historical 
trajectories of people, places, discourses, ideas and objects come 
together to enable some action which in itself alters those historical 
trajectories in some way as those trajectories emanate from this moment 
of social action. Another way to put this is to say simply that nothing 
happens in a social and political vacuum.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">Our
 approach, which we referred to in earlier writing as 'mediated 
discourse analysis' ([15], [16]), is to instigate change by tracing 
social action at the nexus of various trajectories, our action as 
analysts inevitably having social consequences within and without our 
intentions:</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">we
 take an engaged stance; how things are talked about is one of the major
 processes by which our worlds are constructed, legitimated, ratified, 
contested. Therefore, the analysis is a form of action in that world. 
(Scollon and Scollon 2004 : 9)</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">This
 approach brought together research streams which have found affinity in
 this endeavor, many of which have informed linguistic ethnography, 
namely new literacy studies, interactional linguistics, neo‐Vygotskyan 
studies especially those of Wertsch, Scribner, Cole, Lave and Wenger, 
all feeding into the mainstream of linguistic anthropology as a basis 
for taking social action.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">In
 a series of projects undertaken at the University of Alaska in the five
 years of 1978 or so through about 1983, we had as a major aim improving
 the access of Alaska Native people to public institutions – 
educational, medical, legal, and economic – from which they were being 
systematically excluded, largely on the basis of communicative 
technologies and practices ([21]: viii).</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">A nexus analysis as we imagine it embraces a dilemma: there is always far too much to know for anyone to decide <em>a priori</em>
 what is important or relevant to the study at hand. It begins with the 
idea that we are not equal to the task we've set ourselves, especially 
when that task is to not only comprehend but to do something about 
social injustices such as widespread, endemic racism. In a series of 
projects which were necessarily linked in a network of projects of 
others, we came up against the fundamental inadequacy of individual or 
groups of researchers or, in fact, of the research enterprise <em>per se</em> to deal with problems of such comprehensive scope ([21]).</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">Let
 us start with an example from that work. Our concern was with 
institutional racism in the form of prejudicial discrimination against 
Alaska Native1 students at the University of Alaska. Students were 
entering the university in proportion to their percentage of the state 
population (∼17%), but graduating at a much lower percentage (∼1%). We 
found that Alaska Native students (principally Eskimo and Athabaskan) 
from rural villages did best at the university in Fairbanks when they 
lived in one or two of the 'better' (and much older) dormitories; they 
fared poorly when they lived in the newest, flashiest, most 'modern' 
dormitory. Even so, we found that the vast majority were housed in this 
newest dormitory.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">We
 came to this conclusion through a set of research projects that 
combined other researchers' studies of university success, our own 
interviews with the counselling center's specialists who dealt mainly 
with Alaska Native students, and through close ethnographic analysis of 
the ways in which these students lived their daily lives in the dorms, 
in the dining rooms, in the library, and in classrooms, these being the 
principal spaces/situations in which they spent their lives at the 
university. One of our ethnographic methods was to have students draw 
maps of their homes in the village as well as at the university. 
Linguistic ethnographers will be interested to know that 'home' for most
 students encompassed the whole village, in contrast to mainstream 
American students who considered 'home' to be the house or apartment or 
even room they occupied.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">The
 question was: why were Alaska Native students 'choosing' to stay in 
this dorm when other students were 'choosing' the preferable older 
buildings? As we learned, the older dorms were, in fact, the Alaska 
Native students' first choice. And so it was, we thought, clearly a case
 of institutional discrimination. But where was it located? How was it 
happening that some students (white, non‐native ones) were getting their
 first choice and others were not?</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">The
 office which assigns dormitory space assigned that space on a 
first‐past‐the‐post basis. This strategy was chosen, ironically enough, 
so as not to be engaged in discriminatory processes. It just 'happened' 
that rural students (code for Alaska Natives on the whole) were always 
last in getting their applications together. Why was this?</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">In
 most cases the applications of rural students were actually received 
very early in the process; normally this was much before applications 
for out‐of‐state students and before many urban Alaskan students. But, 
applications could not be considered complete until full transcripts 
were received from the students' high school offices.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">For
 many reasons, Alaska rural high schools close very quickly in the 
spring and teachers immediately leave the state. Chief among those 
reasons is that their union contracts don't allow working beyond the 
negotiated agreements. Yes, they did turn in their students' grade 
reports, but unfortunately they did this on the last day of employment 
within that year's contract. With a teacher turn‐over often as high as 
50 percent, students' grades were a relatively low priority for them. 
The net result of this situation was that students' grades were most 
often not collated and sent to the universities to which they'd applied 
until late August when administrators and school staff returned to work 
for the new school year.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">One
 could say the 'cause' of poor university student performance for Alaska
