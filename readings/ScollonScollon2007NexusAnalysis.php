 any information about whether or not he/she had prior convictions.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">Much
 in a nexus analysis is continuous with both traditional ethnography and
 with the ethnography of communication, but the starting point is 
changed and the method for proceeding is also rather different. The 
purpose of a nexus analysis concerning racism, for example, is not to 
set out a rational description of racism and its consequences nor to 
argue that there is no rational basis. Racist acts occur whether or not 
there is any rational basis. Further, nexus analysis does not presume 
that we know where we are likely to find racism in a society or even 
more narrowly within specific events, situations, or actions. Nexus 
analysis begins where racism is enacted in the experience of real social
 actors. Then, after some detailed analysis of these actions, the 
analysis probes outward into the histories of actors, resources, scenes,
 or settings across time and place – first into the past to see how the 
actions are constituted and into the future to work toward shaping 
future actions. Thus the question of 'Where do we start?' is answered 
quite directly: we start where we are and build out from there. If our 
concern is with racist actions, we start with an action which is 
perceived (somehow and by the participants) to be racist.</p><a id="AN0027091507-6" xmlns:translation="urn:EBSCO-Translation"> </a><span class="medium-bold" xmlns:translation="urn:EBSCO-Translation"><h3><a data-auto="ep_link" href="#toc" onclick="FocusElement('toc');" id="hd_toc_AN0027091507-6" title="ETHNOGRAPHIC OBSERVATION IN AN AGE OF SURVEILLANCE">ETHNOGRAPHIC OBSERVATION IN AN AGE OF SURVEILLANCE</a></h3></span><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">Ethnography
 which is premised on bounded cultural groups and languages requires 
both long field engagements and a rich diversity of observational 
techniques. This perspective has been greatly enabled by the 
technologies of recording that have swept through our lives in the 
decades since Bateson and Mead used photography so effectively in Bali 
([<a id="bib2up
					"> </a><a data-auto="ep_link" href="http://web.a.ebscohost.com.scsu.idm.oclc.org/ehost/delivery?sid=60537309-04f3-4824-b10e-b9cba94f1592%40sdc-v-sessmgr02&amp;vid=4&amp;ReturnUrl=http%3a%2f%2fweb.a.ebscohost.com%2fehost%2fdetail%2fdetail%3fvid%3d2%26sid%3d60537309-04f3-4824-b10e-b9cba94f1592%2540sdc-v-sessmgr02%26bdata%3dJnNpdGU9ZWhvc3QtbGl2ZSZzY29wZT1zaXRl#bib2" id="ref_linkbib2" title="2">2</a>]).
 They added silent film to still photography, then sound/color film and 
more recently the small, highly portable sound recorders and video 
recorders which have become, at least for a while, the <em>sine qua non</em>
 of the bulk of linguistic analysis ([12]). The notebook, pen, and 
sketches of a Boas or a Malinowski no longer seem sufficient to us as 
scientific documentation of a culture or a language. We now wish to have
 tape and video recordings, photographs, screen grabs, printouts of 
online discussions, and now even members' own documentary videos of 
their own practices. We ourselves have sought to pioneer new digital 
techniques by which we could both engage our colleagues in a nexus 
analysis while making digital backup recordings of those engagements 
([21]).</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">There
 are problems of convention which accompany these technological changes 
in what our several research paradigms will consider as data and as 
peer‐group reporting. In many ways one could say that 'data' has come to
 mean 'that which can be recorded as sound and/or images and then – and 
this is essential – transcribed so that it can be placed typographically
 silent and supine on the printed page of the dissertation, book, or 
journal article.' As just one example among many, the journal <em>Discourse and Society</em>
 notes in its instructions to authors that 'Analyses should be 
illustrated by several extracts quoted in the text.' No such recorded 
talk (or writing) no transcript no cited text no publishable data no 
article.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">This
 situation has arisen in part, at least, because of our concern for 
scientific objectivity. While we have often wanted to provide broad, 
wide‐angle views of the worlds of the people we have studied, such a 
view has admittedly not been transportable to colleagues and others who 
have not had the immersion experience of the ethnographer. Surveillance 
and recording technologies have allowed us to transport selected and 
carefully focused slices of life out of the original nexus of activity 
for collegial, peer‐reviewable examination in richer, more multimodal 
formats. Unfortunately, as the complexity of what we are able to record 
expands, we consequently lose the sharper focus of more unimodal 
transcriptions. Thus we have collectively been facing the paradox that 
the more we wish to make available for general examination, the less we 
can produce in such transportable formats.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">Conventional
 formats for recording, transcribing, and publishing data are not our 
main concern, however. Nexus analysis and other research frameworks 
which focus on moments of action rather than on abstractable structures 
such as cultures and languages, must remain inherently open to following
 out where the analysis leads the participants. It is not only 
practically difficult to know what one will need to study next and 
where, or with whom, it is theoretically limiting to make such decisions
 in advance of becoming engaged in the actual research. Such <em>a priori</em>
 control of the research agenda is necessarily rejected as a return to 
an earlier stage of ethnographic development, in which the power to make
 such decisions would always lie in the hands of the external researcher
 and his or her academic and professional institutions.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">To
 put this problem a bit differently, while a traditional ethnography 
settled in advance upon a particular group of people as its unit of 
analysis and conducted whatever observations it might conduct within a 
scope of agreed power/social interactions with members of that group, a 
nexus analysis, like other forms of contemporary ethnographic work such 
as linguistic ethnography, engages in a very much broader scope of 
surveillance. Whether that surveillance is unilaterally imposed by 
requirements for analysis and, ultimately, for publication, or mutually 
agreed among all participants as the basis of self‐reflection or even 
for public display, is not relevant. To put it crudely, a nexus analysis
 would like to document or record everything that might be relevant to 
understanding the historical antecedents of a social action as well as 
the unfolding outcomes of that action.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">Where
 recordings in text, sound, images, diagrams, or any other form are 
given permanence, distribution beyond the immediate participants is 
enabled. Such distribution often takes on a life of its own. 
Consequently, documentation/recording in and of itself becomes a weighty
 and active factor in the ongoing engagement surrounding the action 
being analyzed. It is now common to address this problem under the 
rubric of the security or treatment of human subjects.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">There
 is probably no need to elaborate here on the difficulties many 
researchers face in getting their research approved by some form of 
institutional review board (IRB) on the use of human subjects. To cite 
just one example we know of, a student was conducting research involving
