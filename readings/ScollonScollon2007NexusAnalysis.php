U.S. In the U.S. the requirements for human subject clearance insist 
that each subject be informed of the purposes of the research, of their 
own role in the research, and of the guarantees that their privacy will 
neither be disclosed nor be discoverable. And they must sign a document 
that declares their non‐coerced understanding of this research and their
