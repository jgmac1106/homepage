 analysis takes human action rather than language or culture as its unit
 of analysis. We take one specific case to illustrate the methodology as
 well as its continuity with the project of Hymes, and of Boas before 
him, to take action against racism. A nexus analysis takes the 
constitution of human social groups and languages as a problem to be 
examined, shifting the focus away from groups toward action as the prime
 unit of analysis. This shift disrupts power relations between 
ethnographer as participant and observer and those observed who are now 
participants and observers in partnership, with consequences concerning 
when, where, and with whom ethnography can be done, consequences for the
 security of subjects as well as national security. We begin where 
inequality is perceived and analyze the actions that bring that about, 
our analysis itself being a form of action.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">Keywords: Action; ethnography of communication; nexus analysis</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">Dell Hymes wrote 'A Critique of Christopher Caudwell's <em>Illusion and Reality</em>,'1950,
 for his senior honors thesis as an undergraduate because the author 
held presuppositions about primitive peoples and stages of development 
unacceptable to a critical anthropologist ([23]). Throughout his 
distinguished career, which included holding the presidencies of five 
professional associations, Hymes continued this penetrating concern to 
examine our presuppositions in fields of study which focus on human 
life, language and culture, whether these be literature where he began, 
or anthropology, education, sociology, or folklore.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">Nexus
 analysis is our response to Hymes' call three decades ago for each of 
us to reinvent anthropology as 'a personal general anthropology, whose 
function is the advancement of knowledge and the welfare of mankind' 
(1974: 47). It is a term we have come to use for an approach which takes
 human action rather than language or culture as the fulcrum for such 
studies ([20], [21]). Although this does raise acute problems with our 
understanding of what the term 'action' might mean, it allows us to 
focus our attention on issues such as those raised by Hymes. This is 
because the nature of language and the nature of culture are taken as 
problems to be examined rather than as premises. Our purpose in this 
paper is to use one specific case from our own work as an illustrative 
example first, of how a nexus analysis works and secondly, as an example
 of how this approach is continuous with this concern of Hymes as well 
as the concerns of linguistic ethnography as these are now being 
formulated by other scholars (Rampton this issue).</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">We
 will take up our two main points, however, in reverse order. First we 
will make a few comments on the history of ethnography in North America 
as, in part, an outcome of the concern of Franz Boas and many other 
North American ethnographers with the problem of racism. Then we will 
try to illustrate how we first came to our own engagement with both the 
problems of ethnography and the problems of institutional racism in one 
specific case, the participation of Alaska Native students in the 
University of Alaska. It was that network of projects which we were 
involved in during the late 70s and the 80s which led to our formulation
 of the approach we are now calling 'nexus analysis'.</p><a id="AN0027091507-2" xmlns:translation="urn:EBSCO-Translation"> </a><span class="medium-bold" xmlns:translation="urn:EBSCO-Translation"><h3><a data-auto="ep_link" href="#toc" onclick="FocusElement('toc');" id="hd_toc_AN0027091507-2" title="BOUNDED SOCIAL GROUPS, LANGUAGES, AND THE PROBLEM OF RACISM">BOUNDED SOCIAL GROUPS, LANGUAGES, AND THE PROBLEM OF RACISM</a></h3></span><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">Hymes observed that linguists and anthropologists often implicitly fall back on:</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">a
 'Herderian' conception of a world composed of traditional units of 
language‐and‐culture, for lack of another way of seeing the resources of
 language as an aspect of human groups, because we have not thought 
through new ways of seeing how linguistic resources do, in fact, come 
organized in the world. We have no accepted way of joining our 
understanding of inequality with our understanding of the nature of 
language. (Hymes 1996 [1973] : 25)</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">Boasian
 anthropology was based on such a conception of bounded groups and 
languages, and so, while in the work of Boas and his followers combating
 racism with scientific knowledge was a central goal, it was ultimately 
impossible to 'defeat' a racism which also is premised on such groups.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">To
 some extent the premise of bounded language and cultural groups – and 
consequently physical types as well – arose or was at least consonant 
with the focus on remote, small‐scale societies in North American 
anthropology. To investigate the influence of the physical environment 
on a society, Boas spent a year living among bands of Inuit on Baffin 
Island in the Canadian Arctic, during the course of which, in his total 
dependence for survival upon these people, he developed a healthy 
respect for their knowledge, a lasting interest in their ways of living,
 and a determination as a humanist to convey the truth about their 
customs.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">Buttressed
 by his own ethnography and that of his students, Boas set a focused 
anti‐racist activist agenda for ethnography of which little memory had 
remained until quite recently. The foundational premise was that, while 
languages and cultures were recognizable and independent structures of 
codes and social groupings, language, culture, and physical type were 
distributed non‐co‐extensively across the human population. This 
informed the fundamental ethnographic nature of the Boasian struggle 
against racism. American Indian groups were primary sources of 
argumentation and African Americans became active interlocutors and 
recipients of Boas' arguments, long having been targets of American 
racism.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">The
 argument that for no culture could it be said that there was a unique 
language, nor for any language was there a unique culture with which it 
could be identified, was stated succinctly by Boas as early as 1911 ([<a id="bib4up
					"> </a><a data-auto="ep_link" href="http://web.a.ebscohost.com.scsu.idm.oclc.org/ehost/delivery?sid=60537309-04f3-4824-b10e-b9cba94f1592%40sdc-v-sessmgr02&amp;vid=4&amp;ReturnUrl=http%3a%2f%2fweb.a.ebscohost.com%2fehost%2fdetail%2fdetail%3fvid%3d2%26sid%3d60537309-04f3-4824-b10e-b9cba94f1592%2540sdc-v-sessmgr02%26bdata%3dJnNpdGU9ZWhvc3QtbGl2ZSZzY29wZT1zaXRl#bib4" id="ref_linkbib4" title="4">4</a>], [<a id="bib5up
					"> </a><a data-auto="ep_link" href="http://web.a.ebscohost.com.scsu.idm.oclc.org/ehost/delivery?sid=60537309-04f3-4824-b10e-b9cba94f1592%40sdc-v-sessmgr02&amp;vid=4&amp;ReturnUrl=http%3a%2f%2fweb.a.ebscohost.com%2fehost%2fdetail%2fdetail%3fvid%3d2%26sid%3d60537309-04f3-4824-b10e-b9cba94f1592%2540sdc-v-sessmgr02%26bdata%3dJnNpdGU9ZWhvc3QtbGl2ZSZzY29wZT1zaXRl#bib5" id="ref_linkbib5" title="5">5</a>]).
 Most crucial for the anti‐racist agenda, Boas argued that no physical 
type could be associated with any single language or culture. Thus it 
was logically absurd to make cultural or linguistic readings from 
physical type or vice versa. What a person looks like would tell you 
nothing about how they might speak or how they might organize their 
lives and social relationships. This activist anti‐racist vision of Boas
 was furthered in his work with the Kwakiutl largely to prove that 
modern groups were engaged in social progress and cultural change, in 
opposition to the Social Darwinists who conceived of Native Americans as
 primitive people at an early stage of social evolution.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">Ironically,
 while Boas's anti‐racist agenda was first being hewn out of the solid 
rock and ice of Baffin Island and then the forests, sea, and rains of 
the north‐west coast, American popular racism was establishing itself as
 foundational in the service of seizing land and natural resources for 
homesteaders and railroads all across the frontier. In America the 
academic study of people and their languages has been poised as a 
pivotal hinge in the dialectic between popular racism and intellectual 
anti‐racism from the beginning. When Boas began his fieldwork, the North
 American continent was still relatively open for anthropological 
research as well as railroad development, homesteading, gold rushes and 
the like. By contrast, in Europe which Boas had left behind, land was 
fully surveyed and cultural‐linguistic‐physical type homogeneity was 
becoming ideologically enforced through racist political regimes. In a 
tragic dialectic between popular racism and intellectual anti‐racism, 
European 'pioneers' with the aid of the American military, eliminated 
native Americans to carve out space for settlement and 
industrialization. Anthropologists benefited from the 'opening up' of 
the country along with government and commercial interests at the same 
time as they were becoming engaged in opposition to these sometimes 
brutal strategies of national development.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">In
 time anthropologists came to feel dismayed that the argument against 
race, so clearly accepted within their own circles, was at odds with 
public sentiment. Nevertheless, a telling observation, naturally made 
but almost never commented upon at the meetings of the American 
Anthropological Association (AAA), is the overwhelming racial 
homogeneity of the membership of the association itself, despite the 
AAA's 1998 Statement on Race.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">It
 was a kind of complacency that, we think it could be argued, was based 
on the belief that once an argument is clearly and definitively made, 
rational people will simply change their behavior. Late 20th century, 
early 21st century America makes it abundantly clear, alas, that this is
 not the case.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">While
 there had come to be, then perhaps, a certain complacency among some 
anthropologists concerning race as an academic or theoretical issue, 
many anthropologists and linguists had been alarmed at the opening up of
 racial tensions in the U.S. during and just after World War II and 
devoted themselves to an activist opposition to such abuses of human 
justice. Benedict, for example, working with Gene Weltfish, produced a 
pamphlet of 31 pages in 1943 under the title 'The Races of Mankind' 
([14]). The central argument was the argument of Boas and perhaps of all
 American anthropologists at that time: race, culture, language, and 
intelligence were all independently variable – you cannot read any one 
of these from the other. While the booklet was to be distributed to all 
U.S. military as part of their training in racial equality, it was 
suppressed through the efforts of Congressman Andrew J. May. As Price 
puts it:</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">May
 was from Kentucky, and Kentucky was one of three Southern states 
specifically cited in the pamphlet from the Army World War I 
intelligence tests to show that Northern blacks had scored higher than 
Southern whites. (Price 2004 : 113–114)</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">The
 significance of this event is not so much in the blatant display of 
American popular racism. The significance for us is that this 
anti‐racist position was asserted to be a communist position and 
Weltfish was hounded by the FBI as a communist. Thus in February 1950 
when Senator Joe McCarthy declared that he had a list of 200‐some known 
communists in the U.S. government, the platform for the identification 
of anti‐racist work with communism had already been well prepared. Much 
of the FBI's work in the service of McCarthy's anti‐communism was based 
on this identity of communism with anti‐racism, as Price outlines in 
detail (2004). In a few words it was dangerous from the 1940s through at
 least the end of the 1960s to be an ethnographer, more dangerous to 
focus one's attention on cultural and ethnic groups resident within the 
U.S., and most dangerous of all to actively advocate racial equality.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">Price
 comments concerning Marvin Opler, for example, 'The FBI noted with 
concern that he had taught on the faculty at Reed College' (2004: 196). 
In elaboration of the neo‐Hymesian perspective that Rampton (this issue)
 suggests, we point out that Reed College was Dell Hymes's college as 
well as that of one of the authors of this chapter (Suzie Scollon). 
Again to quote Price:</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">McCarthyism
 limited anthropologists' free academic inquiry by targeting, 
stigmatizing, and penalizing those working for racial, gender, ethnic, 
or economic equality. As red‐baiting witch‐hunts spread, a generation of
 social scientists learned to not overtly think under the rubrics of 
Marxist critique, while many in the discipline learned to ignore 
anthropology's natural, and ethically required, activist roles. (Price 
2004 : xiii)</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">Hymes himself, in his preface to the re‐issue of <em>Rethinking Anthropology</em>, recalled the early 50s, when:</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">it
 was risky to discuss [Marxist thought] with people you did not trust. 
(As a graduate student, I kept Marxist books off my shelves and out of 
sight.) (Hymes 1999: vi, cited in Price 2004 : 29)</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">Thus
 the centerpiece of McCarthyist attacks upon anthropologists was their 
championing of racial equality. In this way many anthropologists were 
silenced during the McCarthy era following the war, while others adopted
 the belief, sadly mistaken, that the race argument had been 
definitively won as there was no longer much active discussion within 
anthropological circles. Unfortunately, not only has the problem of 
racism continued to persist, it was somewhat forgotten that the concept 
of a homogeneous cultural or a homogeneous linguistic community was 
originally an outcome of the racist argument which had been 
strategically adopted in developing the contra‐racist Boasian argument. 
Though race was out, cultural groups and language groups remained, with 
ethnography as the preferred tool for examining them.</p><a id="AN0027091507-3" xmlns:translation="urn:EBSCO-Translation"> </a><span class="medium-bold" xmlns:translation="urn:EBSCO-Translation"><h3><a data-auto="ep_link" href="#toc" onclick="FocusElement('toc');" id="hd_toc_AN0027091507-3" title="INVOLVEMENT AND OBJECTIVITY: PEOPLE OR STRUCTURE?">INVOLVEMENT AND OBJECTIVITY: PEOPLE OR STRUCTURE?</a></h3></span><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">While
 there is actually very little upon which ethnographers will agree when 
they seek to define ethnography, one clear commonality is the idea of 
participant‐observation ([16]). Whatever else may occur, ethnography 
brings the analyst 'into' a community and this, in turn, threatens to 
undermine scientific cannons of objectivity and distance. More recently,
 of course, the direction has been reversed as members of communities 
have begun to use ethnography to study their own groups and 'report out'
 to other academic communities (Rampton this issue).</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">Nexus
 analysis shifts the ground of the participant‐observer dilemma which 
is, we would argue, directly an outcome of these two problems: the 
premise that cultures and languages are best conceived of as bounded and
 discrete entities, and the concern for scientific distance or 
objectivity when the scientist takes on the double role of participation
 and observation. Shifting the focus away from groups which are in what 
might be thought of as a guest/host relationship, a nexus analysis takes
 action as the organizing unit of analysis. The boundaries of social 
groups are thus posed as amenable to empirical analysis: under what 
conditions and for whom is it meaningful to construct a boundary? With 
the focus on action, a metaphor of joint partnership in a common 
endeavor becomes more appropriate for the analysis of human activity.</p><a id="AN0027091507-4" xmlns:translation="urn:EBSCO-Translation"> </a><span class="medium-bold" xmlns:translation="urn:EBSCO-Translation"><h3><a data-auto="ep_link" href="#toc" onclick="FocusElement('toc');" id="hd_toc_AN0027091507-4" title="DISRUPTION OF POWER POSITIONS: ETHNOGRAPHY IN THE SERVICE OF WHOM?">DISRUPTION OF POWER POSITIONS: ETHNOGRAPHY IN THE SERVICE OF WHOM?</a></h3></span><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">The
 shift away from premising bounded social groups as the unit of analysis
 of ethnography, to premising action in a joint partnership, disrupts 
the unique position of the analyst and further forces both analysts and 
their partners to examine the power positions of their client‐employers.
 With World War II, Native American people, mostly speakers of Navaho, 
the linguists who worked with them, and anthropologists working at a 
distance on the country's enemies – Benedict on Japan (1946) and Bateson
 and Mead on Germany ([<a id="bib1up
					"> </a><a data-auto="ep_link" href="http://web.a.ebscohost.com.scsu.idm.oclc.org/ehost/delivery?sid=60537309-04f3-4824-b10e-b9cba94f1592%40sdc-v-sessmgr02&amp;vid=4&amp;ReturnUrl=http%3a%2f%2fweb.a.ebscohost.com%2fehost%2fdetail%2fdetail%3fvid%3d2%26sid%3d60537309-04f3-4824-b10e-b9cba94f1592%2540sdc-v-sessmgr02%26bdata%3dJnNpdGU9ZWhvc3QtbGl2ZSZzY29wZT1zaXRl#bib1" id="ref_linkbib1" title="1">1</a>]) – became central in the war effort.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">This
 collaboration with strategic political‐military agencies was not, of 
course, entirely new. The problem of national security and the 
involvement of linguists and anthropologists in wartime surveillance was
 a problem Boas railed against as early as 1919 ([24]). Anthropology 
itself as a field had barely been constituted in the first decade of the
 20th century when World War I introduced a significant dialectic within
 ethnographic work, its location within the academy or in a government 
bureaucracy. American anthropology began its existence housed primarily 
at the Bureau of American Ethnology at the Smithsonian Institution in 
Washington and the Peabody Museum at Harvard. Boas formulated his 
approach to culture working at museum collections and exhibits, but 
fieldwork in the Pacific Northwest led him to put people before theory, 
with the result that he could no longer continue his museum work because
 of the paradigm of cultural evolution that dominated at the Smithsonian
 and other museums.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">It
 was the evolution of kinship that brought about the rift. Lewis Henry 
Morgan had postulated that human societies evolve from matrilineal to 
patrilineal organization. Boas at first tried to account for the mixed 
kinship organization of the Kwakiutl in accord with this theory, but in 
1897 argued instead that the Kwakiutl were adopting the matrilineal 
system of the Tlingit and Tsimshian, their neighbors to the north 
([24]). His interest in cultural diffusion came with a view of cultural 
boundaries as permeable and overlapping. In 1896 he had been appointed 
lecturer in physical anthropology at Columbia.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">Ironically, in a letter to <em>The Nation</em>
 just after the First World War, Boas had castigated four 
anthropologists who, in the course of research in Mexico, looked for 
evidence of German submarine bases and collected intelligence on Mexican
 political figures and German immigrants in Mexico:</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">A
 person ... who uses science as a cover for political spying, who 
demeans himself to pose before a foreign government as an investigator 
and asks for assistance in his alleged researches in order to carry on, 
under this cloak, his political machinations, prostitutes science in an 
unpardonable way and forfeits the right to be classed as a scientist. 
(Wikipedia 2007)</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">The
 Anthropological Society of Washington passed a resolution condemning 
Boas's letter on three counts, one being endangering anthropologists 
abroad who would now come under suspicion as spies. The AAA, of which 
Boas was a founding member, voted to support the Washington society in 
censuring Boas, not rescinding the censure until 2004. The National 
Research Council (NRC), established in 1916 by the National Academy of 
Sciences as a means of drafting scientists to aid the U.S. government in
 preparation for entry into the war in Europe, also seconded the 
censure, leading Boas to resign as AAA representative to the NRC. The 
leader of the anthropologists that Boas had originally castigated was a 
student of a rival from his museum days, now prominent on the NRC. So 
the dialectic of people versus structure, echoed in the dialectic of 
anthropology versus racism, culminates in the dialectic of 
anthropologists in service of war. The die had been cast long before the
 Second World War.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">The role of linguists in World War II is now perhaps well known because of the film <em>Windtalkers</em>.
 Having a Navajo talk to another Navajo was as good a code as any 
cryptographer had been able to invent, and since all Navajos were 'over 
here,' there were no problems of cousins elsewhere who might be employed
 as code‐breakers for the enemy 'over there.' And in this way Native 
American people and the linguists who worked with them became a central 
part of the American war effort.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">Less
 well known now than the 'windtalkers' is the team of linguists who 
rapidly prepared themselves for immediate deployment at the end of the 
war for the purposes of massive scavenging of military and civilian 
records in the defeated nations for the purposes of war crimes trials. 
Ron's own teacher at the University of Michigan, a professor of German 
and head of the Michigan Honors Program, Otto Graf, was one of a small 
group of about a dozen linguists who took an immersion course in 
Japanese and then parachuted into Japan just at surrender to, well, 
plunder anything and everything they could box up and ship home. Charles
 Hockett was drafted into this same general project but for Chinese, not
 Japanese. Note that Graf, an American‐born German and professor of 
German at the University of Michigan, was not chosen for the team which 
carried out the parallel mission in Germany. It was felt safer to train 
'a German' in the Japanese language, however briefly, than to either let
 him serve on the Germany team, or to let any of the thousands of 
perfectly competent and loyal Japanese then languishing in American 
relocation camps, or even those serving in the armed services in Europe,
 serve on the Japan team.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">At
 the end of World War II, Hymes and thousands of other veterans returned
 to college and studied anthropology on the G.I. Bill, mostly unaware 
that more than half of the nation's anthropologists had contributed to 
the war effort ([<a id="bib8up
					"> </a><a data-auto="ep_link" href="http://web.a.ebscohost.com.scsu.idm.oclc.org/ehost/delivery?sid=60537309-04f3-4824-b10e-b9cba94f1592%40sdc-v-sessmgr02&amp;vid=4&amp;ReturnUrl=http%3a%2f%2fweb.a.ebscohost.com%2fehost%2fdetail%2fdetail%3fvid%3d2%26sid%3d60537309-04f3-4824-b10e-b9cba94f1592%2540sdc-v-sessmgr02%26bdata%3dJnNpdGU9ZWhvc3QtbGl2ZSZzY29wZT1zaXRl#bib8" id="ref_linkbib8" title="8">8</a>]). [<a id="bib3up
					"> </a><a data-auto="ep_link" href="http://web.a.ebscohost.com.scsu.idm.oclc.org/ehost/delivery?sid=60537309-04f3-4824-b10e-b9cba94f1592%40sdc-v-sessmgr02&amp;vid=4&amp;ReturnUrl=http%3a%2f%2fweb.a.ebscohost.com%2fehost%2fdetail%2fdetail%3fvid%3d2%26sid%3d60537309-04f3-4824-b10e-b9cba94f1592%2540sdc-v-sessmgr02%26bdata%3dJnNpdGU9ZWhvc3QtbGl2ZSZzY29wZT1zaXRl#bib3" id="ref_linkbib3" title="3">3</a>]<em>Chrysanthemum and the Sword</em>
 (1946) is often cited as the apex of ethnography at a distance, it 
being a study of Japanese 'national character' based on literary, 
artistic, and other distant sources. It was central in the political 
