ample problems there and this is where we and many others first looked. 
But one cause of poor classroom performance was difficult living 
conditions. Other students partying all night throughout the dorm was 
making it impossible for rural students to study and to sleep. Or it 
was, simply, the crowd of other students. One student commented, for 
example, that she would see and have to talk to more people between her 
room and the bathroom in this dorm than the population of her entire 
village. But then one might be inclined to say the cause was poor 
application and acceptance procedures within the university. That office
 was hampered, however, by the poor support provided to these students 
by their home village high schools, many of them newly built and 
staffed.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">We
 found, as we have noted above, that there was no single point at which 
we could address such problems with any sense that this was the fulcrum 
point around which everything else rotated. The problem we faced was 
finding a way to proceed in the face of this kind of complex and 
distributed social problem.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">Nexus
 analysis draws heavily on traditional ethnography; we relied, for 
example, on ethnographies of Yup'ik, Iñupiaq and Athabaskan people 
living in Alaska in that early work. Nexus analysis is perhaps even more
 closely dependent upon work in the ethnography of communication using 
studies of classrooms, social encounters, gatekeeping encounters, legal 
encounters and the like as primary sources for our own contributions to 
that field. Beyond those studies we also relied heavily on political 
scientific research in the analysis of the grounding conditions of 
Alaska in that period: the rapid development of the largest oil field in
 the U.S. along with the attendant Alaska Native Claims Settlement Act2;
 the establishment of rural high schools under a State of Alaska 
anti‐discriminatory legislative mandate; the U.S. national bilingual 
education laws which were just then being mandated for implementation in
 Alaska's cities and rural villages; and, in the broadest circumference,
 U.S.–Soviet Cold War politics which was for many Alaska Native villages
 a family matter because of relatives living on both sides of the 
U.S.‐Soviet national boundary.</p><p class="body-paragraph" data-auto="body_paragraph" xmlns:translation="urn:EBSCO-Translation">A
