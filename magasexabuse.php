<script>
// ====== TABLE FILTERS + TAG CHIPS + WORKS CITED (project template) ======
(function(){
  const table = document.getElementById("mainTable");
  if (!table) return;

  const tbody = table.tBodies[0];
  const rows = Array.from(tbody.rows);

  // Identify category & tags column indexes from headers
  const headers = Array.from(table.tHead.rows[0].cells).map(th => (th.innerText || "").trim().toLowerCase());
  const idxCategory = headers.indexOf("category");
  const idxTags = headers.indexOf("tags");
  const idxSources = headers.indexOf("sources / evidence links");

  const searchBox = document.getElementById("searchBox");
  const categoryFilter = document.getElementById("categoryFilter");
  const tagsFilter = document.getElementById("tagsFilter");
  const clearBtn = document.getElementById("clearFilters");
  const resultCount = document.getElementById("resultCount");

  // ====== CATEGORY DROPDOWN ======
  const populateCategories = () => {
    if (idxCategory < 0 || !categoryFilter) return;
    const current = categoryFilter.value || "";

    categoryFilter.querySelectorAll("option:not(:first-child)").forEach(o => o.remove());

    const cats = new Set();
    rows.forEach(r => {
      const cell = r.cells[idxCategory];
      const val = cell ? cell.innerText.trim() : "";
      if (val) cats.add(val);
    });

    Array.from(cats).sort((a,b)=>a.localeCompare(b)).forEach(c => {
      const opt = document.createElement("option");
      opt.value = c;
      opt.textContent = c;
      categoryFilter.appendChild(opt);
    });

    categoryFilter.value = current;
  };

  // ====== TAG CHIPS ======
  const renderTagChips = () => {
    if (idxTags < 0) return;

    rows.forEach(r => {
      const cell = r.cells[idxTags];
      if (!cell) return;

      if (cell.querySelector(".chip")) return;

      const raw = (cell.innerText || "").trim();
      if (!raw) return;

      const tags = raw
        .split(/[,;|]\s*|\n+/)
        .map(t => t.trim())
        .filter(Boolean);

      if (!tags.length) return;

      cell.innerHTML = "";
      const wrap = document.createElement("div");
      wrap.className = "chips";

      tags.forEach(t => {
        const chip = document.createElement("span");
        chip.className = "chip";
        chip.textContent = t;
        chip.dataset.tag = t.toLowerCase();
        wrap.appendChild(chip);
      });

      cell.appendChild(wrap);
    });
  };

  // ====== CHIP CLICK HANDLER ======
  tbody.addEventListener("click", (e) => {
    const chip = e.target.closest(".chip");
    if (!chip || !tagsFilter) return;

    chip.classList.toggle("active");

    const active = Array.from(tbody.querySelectorAll(".chip.active"))
      .map(c => c.textContent.trim())
      .filter(Boolean);

    tagsFilter.value = active.join(", ");
    applyFilters();
  });

  const highlightActiveChips = () => {
    if (idxTags < 0) return;
    const wanted = (tagsFilter?.value || "")
      .split(",")
      .map(s => s.trim().toLowerCase())
      .filter(Boolean);

    rows.forEach(r => {
      const cell = r.cells[idxTags];
      if (!cell) return;
      cell.querySelectorAll(".chip").forEach(ch => {
        const on = wanted.includes(ch.dataset.tag);
        ch.classList.toggle("active", on);
      });
    });
  };

  // ====== FILTER LOGIC ======
  const rowText = (r) => Array.from(r.cells).map(td => (td.innerText || "").toLowerCase()).join(" | ");

  function applyFilters(){
    const q = (searchBox?.value || "").trim().toLowerCase();
    const cat = (categoryFilter?.value || "").trim();
    const tagStr = (tagsFilter?.value || "").trim().toLowerCase();

    const wantTags = tagStr
      ? tagStr.split(",").map(s => s.trim()).filter(Boolean)
      : [];

    let shown = 0;

    rows.forEach(r => {
      const matchesSearch = !q || rowText(r).includes(q);

      const matchesCat = (idxCategory < 0 || !cat)
        ? true
        : (r.cells[idxCategory]?.innerText.trim() === cat);

      let matchesTags = true;
      if (idxTags >= 0 && wantTags.length) {
        const tagsCell = r.cells[idxTags];
        const hay = (tagsCell ? tagsCell.innerText : "").toLowerCase();
        matchesTags = wantTags.every(t => hay.includes(t));
      }

      const ok = matchesSearch && matchesCat && matchesTags;
      r.style.display = ok ? "" : "none";
      if (ok) shown++;
    });

    if (resultCount) resultCount.textContent = `${shown} / ${rows.length} rows`;
  }

  // ====== CLEAR ======
  clearBtn && clearBtn.addEventListener("click", () => {
    if (searchBox) searchBox.value = "";
    if (categoryFilter) categoryFilter.value = "";
    if (tagsFilter) tagsFilter.value = "";
    tbody.querySelectorAll(".chip.active").forEach(c => c.classList.remove("active"));
    applyFilters();
  });

  searchBox && searchBox.addEventListener("input", applyFilters);
  tagsFilter && tagsFilter.addEventListener("input", () => { applyFilters(); highlightActiveChips(); });
  categoryFilter && categoryFilter.addEventListener("change", () => { applyFilters(); highlightActiveChips(); });

  populateCategories();
  renderTagChips();
  applyFilters();

  // ====== WORKS CITED (APA-ish) ======
  async function fetchMeta(url) {
    const endpoint = "works_cited_meta.php?url=" + encodeURIComponent(url);
    try {
      const res = await fetch(endpoint, { cache: "no-store" });
      if (!res.ok) throw new Error("meta fetch failed");
      return await res.json();
    } catch (e) {
      return null;
    }
  }

  function apaFromLink(a, meta) {
    const author = a.dataset.apaAuthor || (meta && meta.author) || "";
    const date   = a.dataset.apaDate   || (meta && meta.date)   || "";
    const title  = a.dataset.apaTitle  || (meta && meta.title)  || (a.textContent || "").trim();
    const site   = (meta && meta.site) || "";

    const d = date ? `(${date}).` : "(n.d.).";
    const t = title ? `${title}.` : "";
    const s = site ? `${site}.` : "";
    return `${author ? author + " " : ""}${d} ${t} ${s} ${a.href}`;
  }

  async function buildWorksCited() {
    const list = document.getElementById("worksCitedList");
    if (!list || idxSources < 0) return;

    const links = [];
    rows.forEach(r => {
      const cell = r.cells[idxSources];
      if (!cell) return;
      cell.querySelectorAll("a[href]").forEach(a => links.push(a));
    });

    // de-dup by href
    const byHref = new Map();
    links.forEach(a => { if (!byHref.has(a.href)) byHref.set(a.href, a); });

    const entries = [];
    for (const [href, a] of byHref.entries()) {
      const needsMeta = !(a.dataset.apaAuthor || a.dataset.apaDate || a.dataset.apaTitle);
      const meta = needsMeta ? await fetchMeta(href) : null;
      entries.push(apaFromLink(a, meta));
    }

    entries.sort((x,y)=>x.localeCompare(y));

    list.innerHTML = "";
    entries.forEach(txt => {
      const li = document.createElement("li");
      li.textContent = txt.replace(/\s+/g, " ").trim();
      list.appendChild(li);
    });
  }

  buildWorksCited();
})();
</script>

